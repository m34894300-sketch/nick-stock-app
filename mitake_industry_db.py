def _canonical_industry_for_policy(industry: Any) -> str:
    raw = str(industry or "").strip()
    if not raw:
        return ""
    keys = []
    try:
        keys.extend(_industry_aliases(raw))
    except Exception:
        keys.append(raw)
    keys.append(raw.replace(" ", "").replace("／", "/"))
    # 完全命中優先
    for k in keys:
        kk = str(k or "").strip()
        if kk in MITAKE_SECTOR_RULE_CARDS:
            return kk
    # 關鍵字命中第二順位，避免「散熱族群」與「散熱」互相漏掉
    for card_name in MITAKE_SECTOR_RULE_CARDS.keys():
        if card_name and (card_name in raw or raw in card_name):
            return card_name
    return raw


