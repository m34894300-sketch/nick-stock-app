def _clean_code(code: Any) -> str:
    s = str(code or "").strip().replace("=", "").replace('"', "").replace("'", "")
    return s.zfill(4) if s.isdigit() and len(s) <= 4 else s


def _valid_common_code(code: Any) -> bool:
    s = _clean_code(code)
    return 4 <= len(s) <= 6 and s.isdigit() and not s.startswith("00")


def _now_str() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def _connect(db_path: Path | str = DB_PATH) -> sqlite3.Connection:
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    return conn


def _mitake_db_key(db_path: Path | str = DB_PATH) -> str:
    try:
        return str(Path(db_path).resolve())
    except Exception:
        return str(db_path)


def _mitake_db_version(db_path: Path | str = DB_PATH) -> int:
    try:
        p = Path(db_path)
        return int(p.stat().st_mtime_ns) if p.exists() else 0
    except Exception:
        return 0


def _mitake_trim_cache(cache: Dict[Any, Any], max_entries: int = _MITAKE_CACHE_MAX_ENTRIES) -> None:
    try:
        while len(cache) > int(max_entries):
            cache.pop(next(iter(cache)))
    except Exception:
        pass


def clear_mitake_runtime_cache() -> None:
    """清除三竹執行期快取；保留 SQLite 內容。"""
    _MITAKE_MEMBER_BATCH_CACHE.clear()
    _MITAKE_POOL_CACHE.clear()


def init_mitake_industry_db(db_path: Path | str = DB_PATH) -> None:
    conn = _connect(db_path)
    cur = conn.cursor()
    cur.execute("""
        CREATE TABLE IF NOT EXISTS mitake_industry_members (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            industry TEXT NOT NULL,
            code TEXT NOT NULL,
            name TEXT NOT NULL,
            source TEXT DEFAULT 'mitake_app_seed',
            enabled INTEGER DEFAULT 1,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            UNIQUE(industry, code)
        )
    """)
    cur.execute("CREATE INDEX IF NOT EXISTS idx_mitake_industry ON mitake_industry_members(industry)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_mitake_code ON mitake_industry_members(code)")
    conn.commit()
    conn.close()


def upsert_industry_members(
    industry: str,
    members: Iterable[Tuple[str, str]],
    db_path: Path | str = DB_PATH,
    source: str = "mitake_app_seed",
) -> None:
    init_mitake_industry_db(db_path)
    now = _now_str()
    conn = _connect(db_path)
    cur = conn.cursor()
    for code, name in members or []:
        industry_s = str(industry or "").strip()
        code_s = _clean_code(code)
        name_s = str(name or "").strip()
        if not industry_s or not _valid_common_code(code_s) or not name_s:
            continue
        cur.execute("""
            INSERT INTO mitake_industry_members
                (industry, code, name, source, enabled, created_at, updated_at)
            VALUES
                (?, ?, ?, ?, 1, ?, ?)
            ON CONFLICT(industry, code)
            DO UPDATE SET
                name = excluded.name,
                source = excluded.source,
                enabled = 1,
                updated_at = excluded.updated_at
        """, (industry_s, code_s, name_s, source, now, now))
    conn.commit()
    conn.close()





