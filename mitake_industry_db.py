def seed_mitake_industry_db(db_path: Path | str = DB_PATH) -> None:
    """建立 / 補齊三竹族群股池。

    v274 效能修正：
    - 同一個 Streamlit 執行期內，同一 DB path 只 seed 一次。
    - 避免每次 get_mitake_pool_for_sectors 都把全部 MITAKE_CATEGORY_MEMBERS 重寫一遍。
    """
    key = _mitake_db_key(db_path)
    if key in _MITAKE_SEEDED_PATHS and Path(db_path).exists():
        return
    init_mitake_industry_db(db_path)
    for industry, members in MITAKE_CATEGORY_MEMBERS.items():
        upsert_industry_members(industry, members, db_path=db_path)
    _MITAKE_SEEDED_PATHS.add(key)
    clear_mitake_runtime_cache()


def get_mitake_industry_members_batch(
    industries: Iterable[str],
    db_path: Path | str = DB_PATH,
) -> Dict[str, List[Dict[str, str]]]:
    """v274｜批次讀取多個三竹族群成員。

    目的：
    - 掃股雷達深掃時，不能每個族群別名都開一次 SQLite。
    - 一次把所有 alias 查回來，再用 dict 對齊，避免 300 檔股池/多族群時卡頓。
    """
    names: List[str] = []
    seen = set()
    for x in industries or []:
        s = str(x or "").strip()
        if not s or s in seen:
            continue
        names.append(s)
        seen.add(s)
    if not names:
        return {}

    seed_mitake_industry_db(db_path)
    version = _mitake_db_version(db_path)
    cache_key = (_mitake_db_key(db_path), tuple(sorted(names)), version)
    cached = _MITAKE_MEMBER_BATCH_CACHE.get(cache_key)
    if cached is not None:
        return {k: [dict(x) for x in v] for k, v in cached.items()}

    result: Dict[str, List[Dict[str, str]]] = {name: [] for name in names}
    conn = _connect(db_path)
    try:
        # SQLite 預設變數上限常見為 999，分批保守處理。
        chunk_size = 800
        for i in range(0, len(names), chunk_size):
            chunk = names[i:i + chunk_size]
            placeholders = ",".join(["?"] * len(chunk))
            cur = conn.cursor()
            cur.execute(f"""
                SELECT industry, code, name, source, updated_at
                FROM mitake_industry_members
                WHERE enabled = 1 AND industry IN ({placeholders})
                ORDER BY industry, code
            """, tuple(chunk))
            for r in cur.fetchall():
                d = dict(r)
                ind = d.get("industry")
                if ind in result:
                    result[ind].append(d)
    finally:
        conn.close()

    _MITAKE_MEMBER_BATCH_CACHE[cache_key] = {k: [dict(x) for x in v] for k, v in result.items()}
    _mitake_trim_cache(_MITAKE_MEMBER_BATCH_CACHE)
    return result


def get_mitake_industry_members(industry: str, db_path: Path | str = DB_PATH) -> List[Dict[str, str]]:
    """單一族群查詢保留相容；底層改走批次 helper。"""
    name = str(industry or "").strip()
    if not name:
        return []
    return get_mitake_industry_members_batch([name], db_path=db_path).get(name, [])


def get_all_mitake_industries(db_path: Path | str = DB_PATH) -> List[str]:
    seed_mitake_industry_db(db_path)
    conn = _connect(db_path)
    cur = conn.cursor()
    cur.execute("SELECT DISTINCT industry FROM mitake_industry_members WHERE enabled = 1 ORDER BY industry")
    rows = [r["industry"] for r in cur.fetchall()]
    conn.close()
    return rows


def is_mitake_industry(industry: str, db_path: Path | str = DB_PATH) -> bool:
    name = str(industry or "").strip()
    if not name:
        return False
    if name in MITAKE_CATEGORY_MEMBERS:
        return True
    try:
        return bool(get_mitake_industry_members(name, db_path=db_path))
    except Exception:
        return False


def get_mitake_seed_sector_pool() -> Dict[str, List[Tuple[str, str]]]:
    """回傳可直接併入 SECTOR_STOCK_POOL 的三竹類股池。"""
    out: Dict[str, List[Tuple[str, str]]] = {}
    for industry, members in MITAKE_CATEGORY_MEMBERS.items():
        seen = set()
        rows = []
        for code, name in members:
            code_s = _clean_code(code)
            if not _valid_common_code(code_s) or code_s in seen:
                continue
            rows.append((code_s, str(name).strip()))
            seen.add(code_s)
        if rows:
            out[industry] = rows
    return out


def get_mitake_pool_for_sectors(sectors: Iterable[str], db_path: Path | str = DB_PATH) -> Dict[str, List[Dict[str, str]]]:
    """給掃股雷達 extra_pool 使用；v274 批次讀取＋快取。

    修正重點：
    - 先把所有 sector 的 alias 一次展開。
    - 一次性批次 SELECT，而不是在 sector/alias 迴圈裡一直查 DB。
    - 每個 sector 最多保留 MITAKE_RADAR_MAX_STOCKS_PER_SECTOR 檔，避免深掃候選過大。
    """
    sector_list: List[str] = []
    sector_seen = set()
    for sector in sectors or []:
        sector_s = str(sector or "").strip()
        if not sector_s or sector_s in sector_seen:
            continue
        sector_list.append(sector_s)
        sector_seen.add(sector_s)
    if not sector_list:
        return {}

    # seed 只做一次；後續靠 mtime 版本控制 cache。
    seed_mitake_industry_db(db_path)
    version = _mitake_db_version(db_path)
    cache_key = (_mitake_db_key(db_path), tuple(sector_list), version, int(MITAKE_RADAR_MAX_STOCKS_PER_SECTOR))
    cached = _MITAKE_POOL_CACHE.get(cache_key)
    if cached is not None:
        return {k: [dict(x) for x in v] for k, v in cached.items()}

    alias_map: Dict[str, List[str]] = {}
    all_aliases: List[str] = []
    alias_seen = set()
    for sector_s in sector_list:
        aliases = []
        for key in _industry_aliases(sector_s):
            key_s = str(key or "").strip()
            if not key_s:
                continue
            aliases.append(key_s)
            if key_s not in alias_seen:
                all_aliases.append(key_s)
                alias_seen.add(key_s)
        alias_map[sector_s] = aliases

    rows_by_alias = get_mitake_industry_members_batch(all_aliases, db_path=db_path)
    pool: Dict[str, List[Dict[str, str]]] = {}
    for sector_s in sector_list:
        seen_codes = set()
        items: List[Dict[str, str]] = []
        for key in alias_map.get(sector_s, []):
            for r in rows_by_alias.get(key, []) or []:
                code = _clean_code(r.get("code"))
                if not _valid_common_code(code) or code in seen_codes:
                    continue
                items.append({
                    "stock_id": code,
                    "stock_name": str(r.get("name") or "").strip(),
                    "source": "mitake_cache_batch",
                    "matched_industry": str(r.get("industry") or key),
                })
                seen_codes.add(code)
                if len(items) >= int(MITAKE_RADAR_MAX_STOCKS_PER_SECTOR):
                    break
            if len(items) >= int(MITAKE_RADAR_MAX_STOCKS_PER_SECTOR):
                break
        if items:
            pool[sector_s] = items

    _MITAKE_POOL_CACHE[cache_key] = {k: [dict(x) for x in v] for k, v in pool.items()}
    _mitake_trim_cache(_MITAKE_POOL_CACHE)
    return pool


def get_mitake_pool_from_flow_rows(
    flow_rows: Iterable[Dict[str, Any]],
    allowed_states: Optional[Iterable[str]] = None,
    db_path: Path | str = DB_PATH,
) -> Dict[str, List[Dict[str, str]]]:
    """從資金輪動結果中，挑出允許狀態的類股，讀取三竹完整股池。"""
    allowed = set(allowed_states or MITAKE_RADAR_ALLOWED_STATUSES)
    sectors = []
    seen = set()
    for row in flow_rows or []:
        if not isinstance(row, dict):
            continue
        sector = str(row.get("族群") or row.get("industry") or "").strip()
        state = str(row.get("狀態") or row.get("state") or "").strip()
        if not sector or sector in seen or state not in allowed:
            continue
        sectors.append(sector)
        seen.add(sector)
    return get_mitake_pool_for_sectors(sectors, db_path=db_path)


