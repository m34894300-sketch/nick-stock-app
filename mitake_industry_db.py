def _industry_aliases(industry: Any) -> List[str]:
    raw = str(industry or "").strip()
    if not raw:
        return []
    norm = raw.replace(" ", "").replace("／", "/")
    out = [raw, norm]
    for canon, arr in MITAKE_INDUSTRY_ALIASES.items():
        arr_norm = [str(x).replace(" ", "").replace("／", "/") for x in arr]
        if norm == canon.replace(" ", "").replace("／", "/") or norm in arr_norm:
            out.extend(arr)
            out.append(canon)
    seen = set()
    result = []
    for x in out:
        xx = str(x or "").strip()
        if xx and xx not in seen:
            result.append(xx)
            seen.add(xx)
    return result


